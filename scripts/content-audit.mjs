import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const root = fileURLToPath(new URL("../", import.meta.url));
const server = await createServer({ root, configFile: false, logLevel: "error", server: { middlewareMode: true }, appType: "custom" });

try {
  const { defaultCatalog } = await server.ssrLoadModule("/src/application/seed/defaultCatalog.ts");
  const { auditCatalogContent } = await server.ssrLoadModule("/src/application/seed/auditCatalogContent.ts");
  const audit = auditCatalogContent(defaultCatalog);
  if (process.argv.includes("--json")) {
    console.log(JSON.stringify(audit, null, 2));
  } else if (process.argv.includes("--check")) {
    console.log(`${audit.courses} courses; ${audit.cards} cards; ${audit.authoredSupport} authored supports; ${audit.errorCount} structural errors.`);
    for (const error of audit.catalogErrors) console.error(error);
    for (const row of audit.rows) for (const error of row.errors) console.error(`${row.cardId}: ${error}`);
  } else {
    console.log("# Default catalog content audit\n");
    console.log("Generated by `node scripts/content-audit.mjs`. Re-run after changing any default course.\n");
    console.log(`${audit.courses} courses · ${audit.cards} cards · ${audit.authoredSupport} authored supports · ${audit.cards - audit.authoredSupport} fallback supports · ${audit.errorCount} structural errors.\n`);
    console.log("Structural checks cover references, answer safety, provenance, and authored annotation/IPA alignment. Editorial judgments and learning outcomes require separate review; see [Content review](./CONTENT_REVIEW.md).\n");
    for (const course of defaultCatalog.courses) {
      console.log(`## ${course.title} (revision ${course.revision})\n`);
      for (const row of audit.rows.filter((item) => item.courseId === course.id)) {
        console.log(`- **${row.cardId}** — ${row.target}\n  - Prompt: ${row.prompt}\n  - Accepted alternatives: ${row.acceptableAnswers.join(" | ") || "canonical expression only; standard evaluator normalization still applies"}\n  - Support: ${row.learningSupport}; license: ${row.license}; source: ${row.sourceUrl || "UtterLoop Original"}\n  - Structural result: ${row.errors.join("; ") || "passed"}`);
      }
      console.log();
    }
  }
  process.exitCode = audit.errorCount ? 1 : 0;
} finally {
  await server.close();
}
